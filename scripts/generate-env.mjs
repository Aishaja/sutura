/**
 * Reads .env and writes js/admin-env.js for local admin sign-in.
 * Never upload js/admin-env.js to production hosting.
 */
import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = resolve(root, ".env");
const outPath = resolve(root, "js", "admin-env.js");

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i === -1) continue;
    const key = t.slice(0, i).trim();
    let val = t.slice(i + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function escJs(s) {
  return String(s ?? "")
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n");
}

let vars = {};
if (existsSync(envPath)) {
  vars = parseEnv(readFileSync(envPath, "utf8"));
} else {
  console.warn("[sutura] No .env file — copy .env.example to .env and add admin credentials.");
}

const email = vars.ADMIN_EMAIL || "";
const password = vars.ADMIN_PASSWORD || "";
const autoLogin = String(vars.ADMIN_AUTO_LOGIN || "false").toLowerCase() === "true";

const body = `/* AUTO-GENERATED by npm run env — do not commit. Local dev only. */
window.SUTURA_ADMIN_ENV = {
  email: "${escJs(email)}",
  password: "${escJs(password)}",
  autoLogin: ${autoLogin}
};
`;

writeFileSync(outPath, body, "utf8");
console.log("[sutura] Wrote js/admin-env.js" + (email ? ` for ${email}` : " (empty — set ADMIN_EMAIL in .env)"));
